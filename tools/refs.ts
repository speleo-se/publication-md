#!/usr/bin/env node
/**
 * Generate the content repo's ref/ folder: one small markdown file per reference target, so
 * that reference links (`[text](../ref/<ns|unit>/<id>.md)`, spec §3.5) work in any markdown
 * viewer. Each file forwards to its target and lists every place in the corpus that mentions
 * it or has it as a subject — for an entity (a cave, a person …) that is its index.
 *
 *   node tools/refs.ts            # rewrite <content>/ref/ (generated — commit it, never edit it)
 *   node tools/refs.ts --check    # exit 1 if ref/ is missing, stale or has extra files
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { type CorpusUnit, collectRefs, type Mention, type RefEntry, refPath, resolveLabel } from '../lib/src/index.ts'
import { readCorpus, workspaceFromArgs } from './units.ts'

const argv = process.argv.slice(2)
const ws = workspaceFromArgs(argv)
const check = argv.includes('--check')
const SV = ws.config.language === 'sv'
const T = SV
	? { page: 's.', go: 'Gå till', assumed: '(sidan antagen = PDF-sida; numret saknar sidnumrering)', mentions: 'Omnämnanden', subjects: 'Ämne för', unresolved: 'Omnämnanden utan id — att lösa', ext: 'Källa', unit: 'Nummer', part: 'Artikel/figur' }
	: { page: 'p.', go: 'Go to', assumed: '(page assumed = PDF page; the unit has no page labels)', mentions: 'Mentions', subjects: 'Subject of', unresolved: 'Mentions without an id — to resolve', ext: 'Source', unit: 'Unit', part: 'Part/figure' }

const corpus = readCorpus(ws)
const { refs, problems } = collectRefs(corpus)
for (const p of problems) console.error(`${p.level === 'error' ? 'ERROR' : 'warn '} ${p.file}:${p.line ?? ''} ${p.message}`)

const unitName = (u: CorpusUnit) => u.title ?? u.id
const fileLink = (from: string, u: CorpusUnit, file: string) => relative(dirname(from), join(u.folder, file)).split('\\').join('/')
const mentionLine = (from: string, m: Mention) => {
	const where = `${unitName(m.unit)}${m.label ? `, ${T.page} ${m.label}` : ''}${m.of ? ` (${m.of})` : ''}`
	return `- [${where}](${fileLink(from, m.unit, m.file)})${m.text ? ` — ${m.text}` : ''}`
}
const commonText = (e: RefEntry) => {
	const n = new Map<string, number>()
	for (const m of e.mentions) if (m.kind === 'mention' && m.text) n.set(m.text, (n.get(m.text) ?? 0) + 1)
	return [...n].sort((a, b) => b[1] - a[1])[0]?.[0]
}

const files = new Map<string, string>()
for (const e of [...refs.values()].sort((a, b) => refPath(a.target).localeCompare(refPath(b.target)))) {
	const t = e.target
	const path = refPath(t)
	const out = [`<!-- generated by publication-md tools/refs.ts — do not edit; regenerate with: npm run refs -->`, '']
	if (t.kind === 'entity' || t.kind === 'unresolved') {
		const ns = ws.config.refs?.[t.ns]
		const name = t.kind === 'entity' ? commonText(e) : undefined
		out.push(t.kind === 'entity' ? `# ${name ? `${name} — ` : ''}${ns?.title ?? t.ns} ${t.id}` : `# ${ns?.title ?? t.ns}: ${T.unresolved}`, '')
		if (t.kind === 'entity' && ns?.url) out.push(`${T.ext}: <${ns.url.replace('{id}', encodeURIComponent(t.id))}>`, '')
	} else {
		const u = corpus.units.get(t.unit)
		if (!u) continue
		let target: string | undefined
		let title = unitName(u)
		let note = ''
		if (t.kind === 'unit') target = u.publication ? 'publication.md' : u.pages[0]?.name
		if (t.kind === 'page') {
			const r = resolveLabel(u, t.label)
			target = r ? `pageIndex-${String(r.index).padStart(3, '0')}.md` : undefined
			title += `, ${T.page} ${t.label}`
			if (r?.assumed) note = ` ${T.assumed}`
		}
		if (t.kind === 'key') {
			target = u.keys.get(t.key)
			title += ` — ${t.key}`
		}
		out.push(`# ${title}`, '')
		if (target) out.push(`→ ${T.go} [${title}](${fileLink(path, u, target)})${note}`, '')
	}
	const mentions = e.mentions.filter((m) => m.kind === 'mention')
	const subjects = e.mentions.filter((m) => m.kind === 'subject')
	if (subjects.length) out.push(`## ${T.subjects} (${subjects.length})`, '', ...subjects.map((m) => mentionLine(path, m)), '')
	if (mentions.length) out.push(`## ${t.kind === 'unresolved' ? T.unresolved : T.mentions} (${mentions.length})`, '', ...mentions.map((m) => mentionLine(path, m)), '')
	files.set(path, `${out.join('\n').trimEnd()}\n`)
}

const refDir = join(ws.contentRoot, 'ref')
const existing = new Map<string, string>()
const walk = (d: string) => {
	if (!existsSync(d)) return
	for (const e of readdirSync(d, { withFileTypes: true })) {
		const p = join(d, e.name)
		if (e.isDirectory()) walk(p)
		else existing.set(relative(ws.contentRoot, p).split('\\').join('/'), readFileSync(p, 'utf8'))
	}
}
walk(refDir)

if (check) {
	const stale = [...files].filter(([p, c]) => existing.get(p) !== c).map(([p]) => p)
	const extra = [...existing.keys()].filter((p) => !files.has(p))
	for (const p of stale) console.log(`stale or missing: ${p}`)
	for (const p of extra) console.log(`not generated:    ${p}`)
	console.log(`${files.size} ref file(s); ${stale.length + extra.length} out of date${problems.length ? `; ${problems.length} problem(s)` : ''}`)
	process.exit(stale.length + extra.length || problems.some((p) => p.level === 'error') ? 1 : 0)
}
rmSync(refDir, { recursive: true, force: true })
for (const [p, c] of files) {
	mkdirSync(dirname(join(ws.contentRoot, p)), { recursive: true })
	writeFileSync(join(ws.contentRoot, p), c)
}
console.log(`wrote ${files.size} file(s) under ${refDir}${problems.length ? ` (${problems.length} problem(s) above)` : ''}`)
process.exit(problems.some((p) => p.level === 'error') ? 1 : 0)
