#!/usr/bin/env node
/**
 * Generate REGISTRY.md from registry.yaml (the source of truth for known content repos).
 *
 *   node tools/registry.ts           # rewrite REGISTRY.md
 *   node tools/registry.ts --check   # exit 1 if REGISTRY.md is stale
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { parse } from 'yaml'
import { ROOT } from './workspace.ts'

interface Entry {
	name: string
	repo: string
	title?: string
	owner?: string
	copyright?: string
	access?: string
	language?: string
	units?: string
}

const entries = (parse(readFileSync(join(ROOT, 'registry.yaml'), 'utf8')) ?? []) as Entry[]
const cell = (s: string | undefined) => (s ?? '').replaceAll('|', '\\|')
const md = [
	'<!-- generated by tools/registry.ts from registry.yaml — do not edit; regenerate with: npm run registry -->',
	'',
	'# Registry of content repos',
	'',
	'> **Generated file — do not edit.** The source of truth is [`registry.yaml`](registry.yaml); change that',
	'> (add your repo with a pull request — public or private, say how access is obtained) and run',
	'> `npm run registry`.',
	'',
	'Content repos known to use publication-md:',
	'',
	'| Name | Title | Owner / copyright | Access | Language |',
	'|---|---|---|---|---|',
	...entries.map(
		(e) =>
			`| [${cell(e.name)}](${e.repo}) | ${cell(e.title)} | ${cell([e.owner, e.copyright].filter(Boolean).join(' — '))} | ${cell(e.access)} | ${cell(e.language)} |`,
	),
	'',
	'To work on one: `npm run content -- add <repo url>` (see README).',
	'',
].join('\n')

const out = join(ROOT, 'REGISTRY.md')
if (process.argv.includes('--check')) {
	const ok = readFileSync(out, 'utf8') === md
	console.log(ok ? 'REGISTRY.md is current' : 'REGISTRY.md is stale — run: npm run registry')
	process.exit(ok ? 0 : 1)
}
writeFileSync(out, md)
console.log(`wrote REGISTRY.md (${entries.length} repo(s))`)
